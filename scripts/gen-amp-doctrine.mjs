#!/usr/bin/env node
// Generates the Amp doctrine wrappers under adapters/amp/skills/: one
// `<group>-doctrine` skill per group that keeps doctrine documents at its root
// (skills/core/VERIFICATION.md, skills/pm/GATES.md, and so on).
//
// Why a wrapper exists at all. Amp's installer, `amp skill add`, copies only
// directories that contain a SKILL.md. A skill that cites `core/VERIFICATION.md`
// or `GATES.md` therefore arrives without the document it cites. The wrapper
// is a skill directory that carries byte-identical copies of those documents,
// so `amp skill add tqnonline/skills/adapters/amp` brings the doctrine along.
// The skills themselves are never copied: each keeps one home under skills/.
//
// Deterministic output — same input, same bytes — so drift is checkable with
// --check. Mirrors scripts/gen-wiki-stubs.mjs.
//
// Usage:
//   node scripts/gen-amp-doctrine.mjs           # write wrappers
//   node scripts/gen-amp-doctrine.mjs --check   # exit non-zero on drift, write nothing
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const OUT_DIR = 'adapters/amp/skills';
const GENERATOR = 'scripts/gen-amp-doctrine.mjs';
const errors = [];

// Groups are discovered from the tree, in a fixed order, so that adding a
// doctrine file to a group that had none produces a new wrapper without a
// code change here.
const GROUP_ORDER = ['core', 'developer', 'pm', 'branding', 'writing', 'productivity'];

function isDir(p) {
  return existsSync(p) && statSync(p).isDirectory();
}

// Doctrine documents are the Markdown files at a group's root, except the
// group README, which describes the group to a person rather than governing
// its skills.
function doctrineOf(group) {
  const dir = join(root, 'skills', group);
  return readdirSync(dir)
    .filter((entry) => entry.endsWith('.md') && entry !== 'README.md')
    .filter((entry) => statSync(join(dir, entry)).isFile())
    .sort();
}

function skillsOf(group) {
  const dir = join(root, 'skills', group);
  return readdirSync(dir)
    .filter((entry) => existsSync(join(dir, entry, 'SKILL.md')))
    .sort();
}

function titleOf(group, file) {
  const body = readFileSync(join(root, 'skills', group, file), 'utf8');
  const h1 = body.match(/^#\s+(.+)$/m)?.[1]?.trim();
  if (!h1) errors.push(`skills/${group}/${file}: no H1 to title the document by`);
  return h1 ?? file;
}

function listInProse(items) {
  if (items.length <= 1) return items.join('');
  if (items.length === 2) return `${items[0]} and ${items[1]}`;
  return `${items.slice(0, -1).join(', ')}, and ${items[items.length - 1]}`;
}

// Group names as they read in a heading; `pm` is an initialism.
function headingName(group) {
  return group === 'pm' ? 'PM' : group[0].toUpperCase() + group.slice(1);
}

function wrapperSkill(group, files, skills) {
  const name = `${group}-doctrine`;
  const fileList = listInProse(files.map((f) => `\`${f}\``));
  const description =
    `Doctrine documents of the ${group} group in tqnonline/skills, packaged for Amp as ${fileList}. ` +
    `Use when a skill installed from that catalog cites one of these files, or to read the rules the ` +
    `${group} skills work under. ` +
    (group === 'core'
      ? 'Skills in every group cite these documents as `core/<FILE>.md`.'
      : `Skills in the ${group} group cite these documents by bare filename.`);

  const lines = [];
  lines.push('---');
  lines.push(`name: ${name}`);
  lines.push(`description: ${description}`);
  lines.push('---');
  lines.push('');
  lines.push(`# ${headingName(group)} doctrine (model-invoked)`);
  lines.push('');
  lines.push(`<!-- Generated by ${GENERATOR} from skills/${group}/*.md. Do not edit; change the source and regenerate. -->`);
  lines.push('');
  lines.push(
    `This skill carries the doctrine documents that sit at the root of the \`${group}\` group in ` +
      '[tqnonline/skills](https://github.com/tqnonline/skills). Amp installs a skill by copying the one ' +
      'directory that holds its `SKILL.md`, so a document that lives beside the skill directories rather ' +
      'than inside one does not arrive with the skills that cite it. The copies here are byte-identical ' +
      `to the source files under \`skills/${group}/\`; a test in the repository fails when they differ.`,
  );
  lines.push('');
  lines.push('## How a citation resolves');
  lines.push('');
  if (group === 'core') {
    lines.push(
      'A skill from this catalog cites a core document as `core/<FILE>.md`, for example `core/VERIFICATION.md`. ' +
        'Read the file of the same name in this skill\'s directory. Every group may cite core; core cites no group.',
    );
  } else {
    lines.push(
      `A skill in the ${group} group cites one of these documents by bare filename, for example \`${files[0]}\`. ` +
        `When the citing skill's own directory has no file of that name, read the file here. ` +
        'A document with the same filename in another group\'s doctrine skill is a different document; ' +
        'resolve against the group the citing skill belongs to.',
    );
  }
  lines.push('');
  lines.push('## Documents');
  lines.push('');
  for (const file of files) lines.push(`- \`${file}\` — ${titleOf(group, file)}`);
  lines.push('');
  lines.push(`## Skills in the ${group} group`);
  lines.push('');
  lines.push(
    `These are the skills whose citations resolve here. Install any of them with ` +
      `\`amp skill add tqnonline/skills/skills/${group}/<skill>\`, or the whole group with ` +
      `\`amp skill add tqnonline/skills/skills/${group}\`.`,
  );
  lines.push('');
  lines.push(skills.map((s) => `\`${s}\``).join(', '));
  lines.push('');
  return lines.join('\n');
}

// --- build the desired file set --------------------------------------------
const desired = new Map(); // rel path -> content
const groupsWithDoctrine = [];
for (const group of GROUP_ORDER) {
  if (!isDir(join(root, 'skills', group))) continue;
  const files = doctrineOf(group);
  if (files.length === 0) continue;
  groupsWithDoctrine.push(group);
  const dir = `${OUT_DIR}/${group}-doctrine`;
  desired.set(`${dir}/SKILL.md`, wrapperSkill(group, files, skillsOf(group)));
  for (const file of files) desired.set(`${dir}/${file}`, readFileSync(join(root, 'skills', group, file), 'utf8'));
}

for (const [rel, content] of desired) {
  if (rel.endsWith('SKILL.md') && content.split('\n').length > 120) errors.push(`${rel}: generated SKILL.md exceeds 120 lines`);
}

if (errors.length) {
  console.error('gen-amp-doctrine.mjs failed:\n' + errors.map((e) => ' - ' + e).join('\n'));
  process.exit(1);
}

// Files inside a wrapper directory that the generator did not produce are
// stale copies of a document that was renamed or removed at the source.
function existingWrapperFiles() {
  const out = join(root, OUT_DIR);
  if (!isDir(out)) return [];
  const found = [];
  for (const entry of readdirSync(out)) {
    if (!entry.endsWith('-doctrine') || !isDir(join(out, entry))) continue;
    for (const file of readdirSync(join(out, entry))) found.push(`${OUT_DIR}/${entry}/${file}`);
  }
  return found;
}

// --- write or check ---------------------------------------------------------
if (CHECK) {
  const drift = [];
  for (const [rel, content] of [...desired].sort(([a], [b]) => a.localeCompare(b))) {
    const abs = join(root, rel);
    if (!existsSync(abs)) { drift.push(`${rel}: missing`); continue; }
    if (readFileSync(abs, 'utf8') !== content) drift.push(`${rel}: content differs from the source document`);
  }
  for (const rel of existingWrapperFiles()) if (!desired.has(rel)) drift.push(`${rel}: not produced by the generator (stale)`);
  if (drift.length) {
    console.error('gen-amp-doctrine.mjs --check found drift:\n' + drift.map((d) => ' - ' + d).join('\n'));
    process.exit(1);
  }
  console.log(`gen-amp-doctrine.mjs --check OK: ${desired.size} files match (${groupsWithDoctrine.length} doctrine wrappers)`);
  process.exit(0);
}

for (const rel of existingWrapperFiles()) if (!desired.has(rel)) rmSync(join(root, rel));
for (const [rel, content] of desired) {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), content);
}
console.log(`gen-amp-doctrine.mjs OK: wrote ${desired.size} files (${groupsWithDoctrine.length} doctrine wrappers) -> ${OUT_DIR}/`);
