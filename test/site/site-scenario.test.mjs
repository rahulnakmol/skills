import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, statSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root, read, splitFrontmatter, scalar } from './lib.mjs';

// Scenario-consistency: site/example.md is the one canonical enterprise
// example (QuenServe, epic E1 with three features and six stories) every
// skill page's scenario is rebased onto. This suite enforces two things:
//   1. every skill page's frontmatter scenario names the product (QuenServe)
//      or carries at least one of example.md's own ids — so a scenario is
//      never orphaned from the shared product;
//   2. no id shaped like an epic/feature/story id appears anywhere on the
//      site that example.md does not itself define — so a page can never
//      invent a phantom E1-F9 nobody can trace back to the reference page.
//
// The id shape: an epic (E1), optionally a feature suffix (E1-F1) and, on a
// feature, a story suffix (E1-F1-S1). Built as a source string, not a single
// compiled global RegExp, so every call site gets a fresh regex — a shared
// global regex's `lastIndex` state is a classic footgun across repeated
// .test() calls, and this module makes plenty of them.
const ID_SRC = 'E1(?:-F[0-9]+(?:-S[0-9]+)?)?';

function idsIn(text) {
  return new Set([...text.matchAll(new RegExp(`\\b${ID_SRC}\\b`, 'g'))].map((m) => m[0]));
}

function hasCanonicalShapedId(text) {
  return new RegExp(`\\b${ID_SRC}\\b`).test(text);
}

// --- the reference page itself ----------------------------------------------

const EXAMPLE_PATH = 'site/example.md';
const EXAMPLE_RAW = read(EXAMPLE_PATH);
const CANONICAL_IDS = idsIn(EXAMPLE_RAW);

test('site/example.md defines the canonical id set: one epic, three features, six stories', () => {
  assert.equal(CANONICAL_IDS.size, 10,
    `expected 10 canonical ids (E1 + 3 features + 6 stories), found ${CANONICAL_IDS.size}: ${[...CANONICAL_IDS].sort().join(', ')}`);
  assert.ok(CANONICAL_IDS.has('E1'), 'example.md must define the epic id E1');
  for (const feature of ['E1-F1', 'E1-F2', 'E1-F3']) {
    assert.ok(CANONICAL_IDS.has(feature), `example.md must define feature ${feature}`);
  }
  for (const story of ['E1-F1-S1', 'E1-F1-S2', 'E1-F2-S1', 'E1-F2-S2', 'E1-F3-S1', 'E1-F3-S2']) {
    assert.ok(CANONICAL_IDS.has(story), `example.md must define story ${story}`);
  }
});

test('site/example.md names the product QuenServe', () => {
  assert.match(EXAMPLE_RAW, /\bQuenServe\b/, 'example.md must name QuenServe');
});

// --- every skill page's scenario is grounded in the shared product --------

const PLUGIN = JSON.parse(read('.claude-plugin/plugin.json'));
const MANIFEST_SKILL_NAMES = PLUGIN.skills.map((p) => p.split('/').pop());

function assertScenarioGrounded(pagePath, scenario) {
  const ok = /\bQuenServe\b/.test(scenario) || hasCanonicalShapedId(scenario);
  assert.ok(ok,
    `${pagePath}: scenario must name QuenServe or carry a canonical id (E1 / E1-Fn / E1-Fn-Sn), got: ${JSON.stringify(scenario)}`);
}

for (const name of MANIFEST_SKILL_NAMES) {
  const pagePath = `site/_skills/${name}.md`;
  if (!existsSync(join(root, pagePath))) continue; // reported by site-coverage.test.mjs

  test(`${pagePath}: scenario names QuenServe or a canonical id`, () => {
    const { frontmatter } = splitFrontmatter(read(pagePath));
    const scenario = scalar(frontmatter, 'scenario');
    assert.ok(scenario, `${pagePath}: scenario must be present`);
    assertScenarioGrounded(pagePath, scenario);
  });
}

// --- no page uses an id example.md does not define -------------------------
//
// Scoped to every .md/.html page under site/ that is actually authored
// content: site/_data is generated (gitignored, regenerated by
// scripts/gen-*.mjs — see lib.mjs's own header), site/vendor is a
// third-party Jekyll bundle, and site/assets carries no prose. Everything
// else — skill pages, group pages, journey pages, includes, layouts, and the
// top-level pages — is scanned, so a phantom id pasted into a template or an
// includes file is caught exactly the same as one pasted into a skill page.
const EXCLUDED_DIRS = new Set(['_data', 'vendor', 'assets']);

function walkContentFiles(dir, acc = []) {
  for (const entry of readdirSync(join(root, dir))) {
    if (EXCLUDED_DIRS.has(entry)) continue;
    const rel = join(dir, entry);
    if (statSync(join(root, rel)).isDirectory()) { walkContentFiles(rel, acc); continue; }
    if (entry.endsWith('.md') || entry.endsWith('.html')) acc.push(rel);
  }
  return acc;
}

const SITE_CONTENT_FILES = walkContentFiles('site');

test('site/ has the expected shape to scan (sanity: found the known page counts)', () => {
  assert.ok(SITE_CONTENT_FILES.length >= 50,
    `expected at least 50 authored .md/.html files under site/, found ${SITE_CONTENT_FILES.length}`);
  assert.ok(SITE_CONTENT_FILES.includes(EXAMPLE_PATH), 'the file walk must include site/example.md itself');
});

function assertNoUndefinedIds(pageLabel, text, canonicalIds) {
  const used = [...idsIn(text)];
  const notDefined = used.filter((id) => !canonicalIds.has(id));
  assert.deepEqual(notDefined, [],
    `${pageLabel}: uses id(s) site/example.md does not define: ${notDefined.join(', ')}`);
}

for (const rel of SITE_CONTENT_FILES) {
  test(`${rel}: every id used is one site/example.md defines`, () => {
    assertNoUndefinedIds(rel, read(rel), CANONICAL_IDS);
  });
}

// --- reverse diff: every id example.md defines is actually used somewhere --
//
// The forward check above (every id used is defined) says nothing about a
// canonical id nobody threads through — a story example.md declares in its
// hierarchy block but that never appears on an actual skill, group, or
// journey page. This is the complementary direction: every id defined in
// example.md must be used by at least one OTHER page, so the reference page
// never carries an id that is decoration.
function assertNoOrphanCanonicalIds(canonicalIds, usedElsewhere) {
  const orphans = [...canonicalIds].filter((id) => !usedElsewhere.has(id));
  assert.deepEqual(orphans, [],
    `site/example.md defines id(s) no other site page uses: ${orphans.join(', ')}`);
}

test('every id site/example.md defines is used by at least one other site page', () => {
  const usedElsewhere = new Set();
  for (const rel of SITE_CONTENT_FILES) {
    if (rel === EXAMPLE_PATH) continue;
    for (const id of idsIn(read(rel))) usedElsewhere.add(id);
  }
  assertNoOrphanCanonicalIds(CANONICAL_IDS, usedElsewhere);
});

// --- self-test: the check functions themselves, mutated in isolation ------
//
// Same idiom as site-coverage.test.mjs's synthetic fixtures: a small,
// in-memory input is broken one way at a time and the failure is observed,
// without touching real pages or depending on their exact prose.

test('assertScenarioGrounded: a scenario naming QuenServe passes', () => {
  assert.doesNotThrow(() => assertScenarioGrounded('fixture', 'Reviewing QuenServe before Commitment'));
});

test('assertScenarioGrounded: a scenario naming only a canonical id passes', () => {
  assert.doesNotThrow(() => assertScenarioGrounded('fixture', 'Delivering story E1-F1-S1'));
});

test('assertScenarioGrounded mutation: a scenario naming neither is a named failure', () => {
  assert.throws(() => assertScenarioGrounded('fixture', 'Reviewing the offline-sync path'),
    /scenario must name QuenServe or carry a canonical id/);
});

const FIXTURE_CANONICAL_IDS = new Set(['E1', 'E1-F1', 'E1-F1-S1']);

test('assertNoUndefinedIds: ids drawn only from the canonical set pass', () => {
  assert.doesNotThrow(() => assertNoUndefinedIds(
    'fixture', 'Ships story E1-F1-S1 under epic E1.', FIXTURE_CANONICAL_IDS));
});

test('assertNoUndefinedIds mutation (invent an id): an id outside the canonical set is a named failure', () => {
  assert.throws(() => assertNoUndefinedIds(
    'fixture', 'Ships story E1-F1-S1, tracked alongside invented story E1-F9-S1.', FIXTURE_CANONICAL_IDS),
    /uses id\(s\) site\/example\.md does not define: E1-F9-S1/);
});

test('assertNoUndefinedIds mutation (remove an id from example.md): a now-undefined id is a named failure', () => {
  const shrunk = new Set(FIXTURE_CANONICAL_IDS);
  shrunk.delete('E1-F1-S1');
  assert.throws(() => assertNoUndefinedIds('fixture', 'Ships story E1-F1-S1 under epic E1.', shrunk),
    /uses id\(s\) site\/example\.md does not define: E1-F1-S1/);
});

test('assertNoOrphanCanonicalIds: every canonical id used elsewhere passes', () => {
  assert.doesNotThrow(() => assertNoOrphanCanonicalIds(
    FIXTURE_CANONICAL_IDS, new Set(['E1', 'E1-F1', 'E1-F1-S1'])));
});

test('assertNoOrphanCanonicalIds mutation: a canonical id nothing else uses is a named failure', () => {
  assert.throws(() => assertNoOrphanCanonicalIds(
    FIXTURE_CANONICAL_IDS, new Set(['E1', 'E1-F1'])),
    /defines id\(s\) no other site page uses: E1-F1-S1/);
});
